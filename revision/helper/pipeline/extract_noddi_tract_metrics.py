#!/usr/bin/env python3
"""Local-only registration and spatial QC for the MS100 NODDI extension.

The script deliberately has no BIDS/server input argument.  It consumes only a
local source snapshot and the already-completed local AMICO-NODDI run.  Before
accepting any NODDI value it performs four fail-closed checks:

1. Reject qform/sform anatomical-axis or handedness contradictions.
2. Verify the effective affine after the exact legacy tract-mask permute/flips,
   then verify bilateral masks by their world-coordinate centroids.
3. Re-run the legacy DWI->individual transform on TractoFlow FA and compare it
   with the stored ``space-individual`` FA image.
4. Reproduce the original MATLAB tract extraction on stored FA and MD images
   and compare all 48 values per metric/subject with the snapshotted workbooks.

Grouped tract masks are intentionally reoriented as arrays exactly as in the
original MATLAB code.  Raw NIfTI header equality is not substituted for that
operation.  Zero-valued NODDI samples remain valid when they are inside the
transformed AMICO fitting support. The public CLI intentionally does not write
manuscript-facing aggregate tables; those are generated by MATLAB through
``code/generate_all_metric_tables.m``. Historical extraction routines remain
here only to support the explicit legacy FA/MD validation gate.
"""

