def dry_run(args: argparse.Namespace, subjects: list[str]) -> int:
    original_root = args.snapshot_root / "derivatives/TractoFlow_post"
    missing_required = 0
    print(f"mode={args.mode}")
    print(f"subjects={len(subjects)}")
    print("runtime_server_reads=FORBIDDEN")
    print("transform_order=ants_cli_inverseWarp_then_inverseAffine_empirically_validated")
    print(
        "qc_figures="
        + (
            "explicit:" + ",".join(args.qc_subject)
            if args.make_qc_figures and args.qc_subject
            else "one_per_Control_RRMS_PPMS_SPMS"
            if args.make_qc_figures
            else "disabled"
        )
    )
    for workbook in ("GroupTractFA_All.xlsx", "GroupTractMD_All.xlsx"):
        path = args.snapshot_root / "derivatives/derivativesStats" / workbook
        print(f"workbook {workbook} {'PRESENT' if path.is_file() else 'MISSING'} {path}")
        missing_required += int(not path.is_file())
    for subject in subjects:
        paths = subject_paths(args.snapshot_root, args.noddi_root, args.output_root, subject)
        original = grouped_mask_paths(original_root, subject)
        rebuilt = grouped_mask_paths(args.reconstructed_masks_root, subject)
        original_complete, original_missing = mask_completeness(original)
        rebuilt_complete, rebuilt_missing = mask_completeness(rebuilt)
        print(
            f"{subject} original_masks={'COMPLETE' if original_complete else 'MISSING'} "
            f"rebuilt_masks={'COMPLETE' if rebuilt_complete else 'MISSING'}"
        )
        required_inputs = ("t1", "affine", "inverse_warp", "dti_fa", "stored_fa")
        if args.mode in ("full", "maps-only"):
            required_inputs += ("source_support", "noddi_ndi", "noddi_odi", "noddi_fwf")
        for key in required_inputs:
            status = "PRESENT" if paths[key].is_file() else "MISSING"
            print(f"  {status} {key} {paths[key]}")
            missing_required += int(status == "MISSING")
        if original_complete:
            for metric_key in ("stored_fa", "stored_md"):
                if not paths[metric_key].is_file():
                    missing_required += 1
            if not subject.startswith("sub-C") and not paths["lesion"].is_file():
                missing_required += 1
        elif (
            not rebuilt_complete
            and args.mode in ("full", "maps-only")
            and subject not in EXPECTED_MISSING_ORIGINAL_MASKS
        ):
            print(f"  NO_USABLE_MASK_SET original_missing={len(original_missing)} rebuilt_missing={len(rebuilt_missing)}")
            missing_required += 1
        if args.mode in ("full", "maps-only"):
            for role, source, output, interpolation in (
                ("validation_DTI_FA", paths["dti_fa"], paths["validation_fa"], "Linear"),
                ("NODDI_support", paths["source_support"], paths["support"], "GenericLabel"),
                ("NDI", paths["noddi_ndi"], paths["ndi"], "Linear"),
                ("ODI", paths["noddi_odi"], paths["odi"], "Linear"),
                ("FWF", paths["noddi_fwf"], paths["fwf"], "Linear"),
            ):
                command = ants_command(
                    args.ants,
                    source,
                    paths["t1"],
                    output,
                    paths["inverse_warp"],
                    paths["affine"],
                    interpolation,
                )
                print(f"  COMMAND {role}: {shlex.join(command)}")
    print_schema(args.output_root, args.mode)
    print(f"dry_run_missing_required={missing_required}")
    return 1 if missing_required else 0


def write_outputs(
    *,
    args: argparse.Namespace,
    metric_rows: list[dict[str, Any]],
    subject_rows: list[dict[str, Any]],
    fa_rows: list[dict[str, Any]],
    extraction_value_rows: list[dict[str, Any]],
    extraction_summary_rows: list[dict[str, Any]],
    roi_rows: list[dict[str, Any]],
    geometry_rows: list[dict[str, Any]],
    command_rows: list[dict[str, Any]],
    figure_rows: list[dict[str, Any]],
    metadata: dict[str, Any],
) -> None:
    selected = [args.one_subject] if args.one_subject else list(args.subject)
    if selected:
        token = hashlib.sha256(
            ("\n".join(sorted(selected)) + "\n").encode("utf-8")
        ).hexdigest()[:12]
        aggregate_root = args.output_root / "subset_runs" / f"n{len(selected)}_{token}"
    else:
        aggregate_root = args.output_root
    results = aggregate_root / "results"
    qc = aggregate_root / "qc"
    primary = [row for row in metric_rows if row["analysis_variant"] == "primary_original_masks"]
    sensitivity = [
        row for row in metric_rows if row["analysis_variant"] == "reconstructed_mask_sensitivity"
    ]
    atomic_write_csv(results / "noddi_tract_metrics_tidy.csv", METRIC_COLUMNS, metric_rows)
    atomic_write_csv(results / "noddi_tract_metrics_primary.csv", METRIC_COLUMNS, primary)
    atomic_write_csv(
        results / "noddi_tract_metrics_reconstructed_mask_sensitivity.csv",
        METRIC_COLUMNS,
        sensitivity,
    )
    for metric in NODDI_METRICS:
        atomic_write_csv(
            results / f"GroupTract{metric}_All.csv",
            ("SubjectID",) + LEGACY_COLUMNS,
            build_og_wide_rows(metric_rows, metric),
        )
    atomic_write_csv(
        results / "GroupTractODI_P10_Sensitivity.csv",
        ("SubjectID",) + ODI_P10_SENSITIVITY_COLUMNS,
        build_odi_p10_sensitivity_rows(metric_rows),
    )
    atomic_write_csv(
        results / "GroupTractODI_P10_All.csv",
        ("SubjectID",) + LEGACY_COLUMNS,
        build_odi_p10_og_wide_rows(metric_rows),
    )
    atomic_write_csv(qc / "subject_status.csv", SUBJECT_STATUS_COLUMNS, subject_rows)
    atomic_write_csv(qc / "fa_transform_validation.csv", FA_VALIDATION_COLUMNS, fa_rows)
    atomic_write_csv(
        qc / "extraction_validation_values.csv", EXTRACTION_VALUE_COLUMNS, extraction_value_rows
    )
    atomic_write_csv(
        qc / "extraction_validation_summary.csv",
        EXTRACTION_SUMMARY_COLUMNS,
        extraction_summary_rows,
    )
    atomic_write_csv(qc / "tract_roi_qc.csv", ROI_QC_COLUMNS, roi_rows)
    atomic_write_csv(qc / "geometry_qc.csv", MAP_QC_COLUMNS, geometry_rows)
    atomic_write_csv(qc / "ants_commands.csv", COMMAND_COLUMNS, command_rows)
    atomic_write_csv(qc / "qc_figure_manifest.csv", QC_FIGURE_COLUMNS, figure_rows)
    atomic_write_json(results / "run_metadata.json", metadata)


