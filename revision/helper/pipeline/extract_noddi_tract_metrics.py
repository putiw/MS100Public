    parser.add_argument("--noddi-root", type=Path, default=DEFAULT_NODDI_ROOT)
    parser.add_argument("--output-root", type=Path, default=ANALYSIS_ROOT)
    parser.add_argument("--reconstructed-masks-root", type=Path, default=None)
    parser.add_argument("--ants", type=Path, default=DEFAULT_ANTS)
