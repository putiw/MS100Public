def main() -> int:
    global EXPECTED_MISSING_ORIGINAL_MASKS
    parser = build_parser()
    args = parser.parse_args()
    if not 0.0 <= args.parameter_bound_tolerance <= MAX_PARAMETER_BOUND_TOLERANCE:
        parser.error(
            "--parameter-bound-tolerance must be between 0 and 1e-6; "
            "NODDI maps are never clipped and reported aggregates must be in [0,1]"
        )
    if args.one_subject and args.subject:
        parser.error("--one-subject and --subject are mutually exclusive")
    if args.qc_subject and not args.make_qc_figures:
        parser.error("--qc-subject requires --make-qc-figures")
    if args.make_qc_figures and args.mode == "validate-extraction":
        parser.error("--make-qc-figures requires --mode maps-only")
    selected = [args.one_subject] if args.one_subject else args.subject
    try:
        args.snapshot_root = guard_local_path(args.snapshot_root, "snapshot root", require_exists=True)
        args.noddi_root = guard_local_path(args.noddi_root, "NODDI root", require_exists=True)
        args.output_root = guard_local_path(args.output_root, "output root")
        args.ants = guard_local_path(args.ants, "antsApplyTransforms", require_exists=True)
        args.reconstructed_masks_root = guard_local_path(
            args.reconstructed_masks_root or args.output_root / "reconstructed_masks",
            "reconstructed masks root",
        )
        if is_relative_to(args.output_root, args.snapshot_root) or is_relative_to(
            args.output_root, args.noddi_root
        ):
            raise PipelineError("Output root must not be inside either read-only input tree")
        subjects = discover_subjects(args.noddi_root, selected)
        full_subjects = discover_subjects(args.noddi_root, None)
        EXPECTED_MISSING_ORIGINAL_MASKS = discover_original_mask_exclusions(
            args.snapshot_root, full_subjects
        )
        qc_subjects = {
            value if value.startswith("sub-") else f"sub-{value}" for value in args.qc_subject
        }
        outside_selection = sorted(qc_subjects.difference(subjects))
        if outside_selection:
            raise PipelineError(
                "--qc-subject must also be in the selected processing set: "
                + ", ".join(outside_selection)
            )
        if args.print_schema:
            print_schema(args.output_root, args.mode)
            if not args.dry_run:
                return 0
        if args.dry_run:
            return dry_run(args, subjects)
        with run_lock(args.output_root / "logs/run_noddi_tract_pipeline.lock"):
            return execute(args, subjects)
    except PipelineError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:
        print(f"UNEXPECTED ERROR: {exc}", file=sys.stderr)
        traceback.print_exc()
        return 3


if __name__ == "__main__":
    raise SystemExit(main())
